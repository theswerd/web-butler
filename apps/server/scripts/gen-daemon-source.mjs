#!/usr/bin/env node
// Embeds the VM daemon (vm-daemon/daemon.mjs) and its supervisor script
// into src/daemon-source.gen.ts so the server — which runs on Cloudflare
// Workers, where there is no filesystem — can write them to VMs and serve
// them at /api/daemon/source. The version is a content hash: bumping the
// daemon is just editing daemon.mjs and re-running this script (wired into
// predev/prestart/predeploy, so it stays fresh automatically).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const daemon = readFileSync(join(root, 'vm-daemon/daemon.mjs'), 'utf8');
const ensure = readFileSync(join(root, 'vm-daemon/ensure-daemon.sh'), 'utf8');

const version = createHash('sha256')
  .update(daemon)
  .update(ensure)
  .digest('hex')
  .slice(0, 12);

const out =
  '// GENERATED by scripts/gen-daemon-source.mjs — do not edit.\n' +
  '// Source of truth: vm-daemon/daemon.mjs and vm-daemon/ensure-daemon.sh.\n' +
  `export const DAEMON_VERSION = ${JSON.stringify(version)};\n` +
  `export const DAEMON_SOURCE = ${JSON.stringify(daemon)};\n` +
  `export const ENSURE_DAEMON_SCRIPT = ${JSON.stringify(ensure)};\n`;

writeFileSync(join(root, 'src/daemon-source.gen.ts'), out);
console.log(`daemon-source.gen.ts written (version ${version})`);
